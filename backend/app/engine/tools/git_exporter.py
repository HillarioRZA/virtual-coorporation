"""
Autonomous Git Exporter and Local-to-Remote Bridge Subsystem.
Menangani inisialisasi git, penegakan auto-.gitignore, dan commit atomik
pada direktori projects_output/<project_id> saat tiket Kanban DONE atau PR MERGED.
"""

import asyncio
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple
from app.core.config import BASE_DIR
from app.core.logger import logger

_DEFAULT_GITIGNORE: str = """# Auto-generated by Virtual Corporation Git Exporter
node_modules/
.next/
__pycache__/
.venv/
venv/
.env
.env.local
*.pyc
*.pyo
.DS_Store
dist/
build/
.pytest_cache/
coverage/
"""


class GitExporter:
    """Manajer ekspor dan sinkronisasi Git lokal ke remote repository."""

    @staticmethod
    def ensure_gitignore(project_dir: Path) -> None:
        """Memastikan berkas .gitignore ada dan mengecualikan dependensi berat/rahasia."""
        try:
            gi_path = project_dir / ".gitignore"
            if not gi_path.exists():
                gi_path.write_text(_DEFAULT_GITIGNORE, encoding="utf-8")
                logger.info(f"Auto-.gitignore dibuat pada [{project_dir.name}].")
            else:
                existing = gi_path.read_text(encoding="utf-8", errors="ignore")
                missing = []
                for entry in ["node_modules/", ".next/", "__pycache__/", ".venv/", ".env"]:
                    if entry not in existing:
                        missing.append(entry)
                if missing:
                    gi_path.write_text(existing.rstrip() + "\n" + "\n".join(missing) + "\n", encoding="utf-8")
        except (IOError, OSError) as err:
            logger.warning(f"Gagal memastikan .gitignore pada [{project_dir}]: {err}")

    async def _run_git_cmd(self, cmd: List[str], cwd: Path) -> Tuple[int, str, str]:
        """Helper eksekusi perintah Git asinkron dengan timeout."""
        try:
            proc = await asyncio.create_subprocess_exec(
                "git",
                *cmd,
                cwd=str(cwd),
                stdout=asyncio.subprocess.PIPE,
                stderr=asyncio.subprocess.PIPE,
            )
            stdout, stderr = await asyncio.wait_for(proc.communicate(), timeout=30.0)
            return proc.returncode or 0, stdout.decode("utf-8", errors="ignore"), stderr.decode("utf-8", errors="ignore")
        except (asyncio.TimeoutError, OSError, Exception) as err:
            logger.debug(f"Eksekusi git {cmd} gagal: {err}")
            return -1, "", str(err)

    async def export_project_checkpoint(
        self,
        project_id: str,
        commit_message: str = "chore(ai): autonomous milestone update",
    ) -> Dict[str, Any]:
        """
        Melakukan sinkronisasi Git atomik pada workspace lokal proyek.
        Dipanggil otomatis saat PR berstatus MERGED atau tiket Kanban berstatus DONE.
        """
        project_dir = BASE_DIR / "projects_output" / project_id
        if not project_dir.exists() or not project_dir.is_dir():
            return {"status": "SKIPPED", "reason": f"Direktori proyek [{project_id}] belum ada."}

        self.ensure_gitignore(project_dir)

        # Inisialisasi repo jika belum ada .git
        git_dir = project_dir / ".git"
        if not git_dir.exists():
            code, _, err = await self._run_git_cmd(["init"], cwd=project_dir)
            if code != 0:
                return {"status": "FAILED", "reason": f"git init gagal: {err}"}
            await self._run_git_cmd(["config", "user.name", "AI Agent Organization"], cwd=project_dir)
            await self._run_git_cmd(["config", "user.email", "agent@virtualcorp.local"], cwd=project_dir)

        # Stage and check changes
        await self._run_git_cmd(["add", "-A"], cwd=project_dir)
        code, status_out, _ = await self._run_git_cmd(["status", "--porcelain"], cwd=project_dir)
        if not status_out.strip():
            logger.info(f"Workspace [{project_id}] bersih, tidak ada perubahan berkas untuk di-commit.")
            return {"status": "CLEAN", "project_id": project_id}

        # Commit atomik
        c_code, c_out, c_err = await self._run_git_cmd(["commit", "-m", commit_message], cwd=project_dir)
        if c_code == 0:
            logger.info(f"Git commit sukses untuk proyek [{project_id}]: '{commit_message}'")
            return {"status": "COMMITTED", "project_id": project_id, "message": commit_message}
        else:
            logger.warning(f"Git commit gagal untuk proyek [{project_id}]: {c_err}")
            return {"status": "FAILED", "project_id": project_id, "error": c_err}


git_exporter = GitExporter()
